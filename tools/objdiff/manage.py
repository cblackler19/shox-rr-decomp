
#!/usr/bin/env python3
"""Manage Shox retail function manifests and objdiff build configuration."""

import argparse
import json
import re
import sys
from pathlib import Path, PurePosixPath

ROOT = Path(__file__).resolve().parents[2]
MANIFEST = ROOT / "config/retail/functions.json"

NINJA_OUTPUT = ROOT / "build.ninja"
OBJDIFF_OUTPUT = ROOT / "objdiff.json"

FUNCTION_NAME = re.compile(r"func_([0-9A-F]{8})")


def parse_hex(value: str, field: str) -> int:
    if not isinstance(value, str) or not re.fullmatch(
        r"0[xX][0-9a-fA-F]+", value
    ):
        raise ValueError(f"{field}: expected a hexadecimal string")

    return int(value, 16)


def validate_path(value: str, field: str) -> Path:
    if not isinstance(value, str):
        raise ValueError(f"{field}: expected a string")

    path = PurePosixPath(value)

    if (
        path.is_absolute()
        or "\\" in value
        or ":" in value
        or any(part in (".", "..") for part in value.split("/"))
        or any(char in value for char in " $:#\r\n\t")
        or not value
    ):
        raise ValueError(f"{field}: unsafe path: {value!r}")

    resolved = (ROOT / value).resolve()

    if not resolved.is_relative_to(ROOT.resolve()):
        raise ValueError(f"{field}: path escapes repository")

    return resolved


def load_manifest() -> dict:
    if not MANIFEST.is_file():
        raise FileNotFoundError(f"Missing manifest: {MANIFEST}")

    manifest = json.loads(MANIFEST.read_text(encoding="utf-8"))

    if not isinstance(manifest, dict):
        raise ValueError("Manifest must be a JSON object")

    if manifest.get("version") != "retail":
        raise ValueError("Only the retail version is supported")

    text_config = manifest["text"]
    text_start = parse_hex(text_config["address"], "text.address")
    text_size = parse_hex(text_config["size"], "text.size")
    text_end = text_start + text_size

    if text_start != 0x00100000 or text_size != 0x001D47C4:
        raise ValueError("Unexpected retail .text boundaries")

    compiler = manifest["compiler"]
    validate_path(compiler["executable"], "compiler.executable")

    flags = compiler["flags"]

    if (
        not isinstance(flags, list)
        or not flags
        or any(
            not isinstance(flag, str)
            or not re.fullmatch(r"-[A-Za-z0-9_=.+-]+", flag)
            for flag in flags
        )
    ):
        raise ValueError("Invalid compiler flags")

    functions = manifest["functions"]

    if not isinstance(functions, list):
        raise ValueError("functions must be an array")

    names = set()
    sources = set()
    ranges = []

    for entry in functions:
        name = entry["name"]
        match = (
            FUNCTION_NAME.fullmatch(name)
            if isinstance(name, str)
            else None
        )

        if match is None:
            raise ValueError(f"Invalid function name: {name!r}")

        address = parse_hex(entry["address"], f"{name}.address")
        size = parse_hex(entry["size"], f"{name}.size")
        source_name = entry["source"]

        if address != int(match.group(1), 16):
            raise ValueError(f"{name}: name/address mismatch")

        if address % 4 or size <= 0 or size % 4:
            raise ValueError(f"{name}: invalid alignment or size")

        if address < text_start or address + size > text_end:
            raise ValueError(f"{name}: outside retail .text")

        if name in names:
            raise ValueError(f"Duplicate function: {name}")

        if not isinstance(source_name, str) or not source_name.startswith(
            "src/retail/"
        ) or not source_name.endswith(".cpp"):
            raise ValueError(f"{name}: unexpected source path")

        source_path = validate_path(source_name, f"{name}.source")

        if not source_path.is_file():
            raise FileNotFoundError(
                f"{name}: source file not found: {source_path}"
            )

        if source_name in sources:
            raise ValueError(f"Duplicate source: {source_name}")

        names.add(name)
        sources.add(source_name)
        ranges.append((address, address + size, name))

    ranges.sort()

    for previous, current in zip(ranges, ranges[1:]):
        if current[0] < previous[1]:
            raise ValueError(
                f"Overlapping functions: {previous[2]} and {current[2]}"
            )

    return manifest


def generate_ninja(manifest: dict) -> str:
    compiler = manifest["compiler"]["executable"]
    flags = " ".join(manifest["compiler"]["flags"])

    lines = [
        "# Generated by tools/objdiff/manage.py. Do not edit.",
        "",
        f"compiler = {compiler}",
        f"cxxflags = {flags}",
        "",
        "rule cxx",
        "  command = $compiler $cxxflags -c -o $out $in",
        "  description = CXX $in",
        "",
    ]

    outputs = []

    for entry in manifest["functions"]:
        name = entry["name"]
        source = entry["source"]
        output = f"build/objdiff/base/{name}.o"

        lines.append(f"build {output}: cxx {source}")
        outputs.append(output)

    if outputs:
        lines.extend(["", "default " + " ".join(outputs)])

    lines.append("")
    return "\n".join(lines)


def generate_objdiff(manifest: dict) -> str:
    units = []

    for entry in manifest["functions"]:
        name = entry["name"]

        units.append({
            "name": f"retail/{name}",
            "target_path": f"build/objdiff/target/{name}.o",
            "base_path": f"build/objdiff/base/{name}.o",
            "source_path": entry["source"],
        })

    config = {
        "$schema": (
            "https://raw.githubusercontent.com/encounter/"
            "objdiff/main/config.schema.json"
        ),
        "custom_make": "ninja",
        "build_target": False,
        "build_base": True,
        "watch_patterns": [
            "src/**/*.cpp",
            "src/**/*.h",
            "build.ninja",
        ],
        "ignore_patterns": ["build/**/*"],
        "units": units,
    }

    return json.dumps(config, indent=2) + "\n"


def write_if_changed(path: Path, content: str) -> bool:
    if path.is_file() and path.read_text(encoding="utf-8") == content:
        print(f"UNCHANGED {path.relative_to(ROOT)}")
        return False

    path.write_text(content, encoding="utf-8", newline="\n")
    print(f"UPDATED   {path.relative_to(ROOT)}")
    return True


def sync(manifest: dict) -> None:
    # All validation has already completed before output files are written.
    ninja_content = generate_ninja(manifest)
    objdiff_content = generate_objdiff(manifest)

    (ROOT / "build/objdiff/base").mkdir(parents=True, exist_ok=True)
    (ROOT / "build/objdiff/target").mkdir(parents=True, exist_ok=True)

    write_if_changed(NINJA_OUTPUT, ninja_content)
    write_if_changed(OBJDIFF_OUTPUT, objdiff_content)


def list_functions(manifest: dict) -> None:
    functions = manifest["functions"]

    if not functions:
        print("No functions registered.")
        return

    print(f"{'FUNCTION':<20} {'ADDRESS':<12} {'SIZE':>8}")
    print("-" * 44)

    for entry in functions:
        size = parse_hex(entry["size"], "size")
        print(
            f"{entry['name']:<20} "
            f"{entry['address']:<12} "
            f"{size:>8}"
        )

    print()
    print(f"Registered functions: {len(functions)}")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "command",
        choices=["validate", "sync", "list"],
    )
    args = parser.parse_args()

    try:
        manifest = load_manifest()

        if args.command == "validate":
            print("Manifest validation: PASS")
            print(f"Functions: {len(manifest['functions'])}")

        elif args.command == "sync":
            sync(manifest)

        elif args.command == "list":
            list_functions(manifest)

    except (
        OSError,
        ValueError,
        KeyError,
        TypeError,
        json.JSONDecodeError,
    ) as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1

    return 0


if __name__ == "__main__":
    sys.exit(main())
